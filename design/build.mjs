// Builds every platform's design tokens from design/tokens (W3C DTCG format)
// with Style Dictionary. `--check` builds into a temporary folder and fails
// when a committed output is stale.
import { mkdtemp, readFile, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";
import StyleDictionary from "style-dictionary";
import { fileHeader, formattedVariables } from "style-dictionary/utils";

const designDir = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.dirname(designDir);
const tokens = (name) => path.join(designDir, "tokens", name);

export const outputs = {
  desktopCss: "apps/desktop/src/generated/design/tokens.css",
  desktopDarkCss: "apps/desktop/src/generated/design/tokens.dark.css",
  desktopJson: "apps/desktop/src/generated/design/tokens.json",
  corePalette: "crates/isct-core/src/schedule/course_palette.rs",
  swiftLight: "design/dist/ios/IsctTokens.swift",
  swiftDark: "design/dist/ios/IsctTokensDark.swift",
  composeLight: "design/dist/android/IsctTokens.kt",
  composeDark: "design/dist/android/IsctTokensDark.kt",
};

const group =
  (...names) =>
  (token) =>
    names.includes(token.path[0]);
const not = (filter) => (token) => !filter(token);
const isTint = (token) =>
  token.path[0] === "course" && token.path[1] === "tint";
const isPalette = (token) =>
  token.path[0] === "course" && token.path[1] === "palette";

StyleDictionary.registerTransform({
  // CSS names stay the public variables shells and per-site CSS already use.
  name: "name/isct-css",
  type: "name",
  transform: ({ path: p }) =>
    p[0] === "color"
      ? p.slice(1).join("-")
      : p[0] === "shadow"
        ? "shadow"
        : p[0] === "font"
          ? ["font", ...p.slice(2)].join("-")
          : p.join("-"),
});
StyleDictionary.registerTransform({
  name: "value/percent",
  type: "value",
  filter: isTint,
  transform: (token) => `${Math.round(token.$value * 100)}%`,
});
StyleDictionary.registerTransform({
  name: "size/swift/px",
  type: "value",
  filter: (token) => token.$type === "dimension",
  transform: (token) => `CGFloat(${parseFloat(token.$value)})`,
});
StyleDictionary.registerTransform({
  name: "size/compose/px",
  type: "value",
  filter: (token) => token.$type === "dimension",
  transform: (token) => `${parseFloat(token.$value)}.dp`,
});

const darkSelectors = [
  [':root[data-appearance="dark"]'],
  [
    "@media (prefers-color-scheme: dark)",
    ':root:not([data-appearance="light"])',
  ],
];
StyleDictionary.registerFormat({
  // The dark theme applies when chosen, or when the system is dark and the
  // user has not chosen light.
  name: "css/isct-dark",
  format: async ({ dictionary, file }) => {
    const header = await fileHeader({ file });
    const body = (depth) =>
      formattedVariables({ format: "css", dictionary, usesDtcg: true })
        .split("\n")
        .map((line) => "  ".repeat(depth - 1) + line)
        .join("\n");
    const blocks = darkSelectors.map((selectors) => {
      const depth = selectors.length;
      const open = selectors
        .map((selector, i) => `${"  ".repeat(i)}${selector} {`)
        .join("\n");
      const close = selectors
        .map((_, i) => `${"  ".repeat(depth - 1 - i)}}`)
        .join("\n");
      return `${open}\n${"  ".repeat(depth)}color-scheme: dark;\n${body(depth)}\n${close}`;
    });
    return `${header}${blocks.join("\n")}\n`;
  },
});
StyleDictionary.registerFormat({
  name: "rust/course-palette",
  format: ({ dictionary }) => {
    const colors = dictionary.allTokens
      .filter(isPalette)
      .sort((a, b) => Number(a.path[2]) - Number(b.path[2]))
      .map((token) => `"${token.$value}"`);
    return [
      "// Do not edit directly; generated by design/build.mjs from design/tokens/course.json.",
      `pub const COURSE_PALETTE: [&str; ${colors.length}] = [`,
      `    ${colors.join(", ")},`,
      "];",
      "",
    ].join("\n");
  },
});

const cssTransforms = [
  "attribute/cti",
  "name/isct-css",
  "value/percent",
  "color/css",
  "shadow/css/shorthand",
  "fontFamily/css",
];
const swiftTransforms = [
  "attribute/cti",
  "name/camel",
  "color/ColorSwiftUI",
  "size/swift/px",
];
const composeTransforms = [
  "attribute/cti",
  "name/camel",
  "color/composeColor",
  "size/compose/px",
];
// Phones take fonts and shadows from the platform; the tonal scale is Mantine's.
const mobileToken = group("color", "radius", "course");

async function build(out) {
  const at = (file) => path.join(out, path.dirname(file)) + path.sep;
  const name = (file) => path.basename(file);
  const options = { usesDtcg: true, log: { verbosity: "silent" } };
  const light = [
    tokens("color.light.json"),
    tokens("course.json"),
    tokens("shape.json"),
  ];
  const runs = [
    new StyleDictionary({
      ...options,
      source: light,
      platforms: {
        desktop: {
          transforms: cssTransforms,
          buildPath: at(outputs.desktopCss),
          files: [
            {
              destination: name(outputs.desktopCss),
              format: "css/variables",
              filter: (token) =>
                group("color", "shadow", "radius", "font", "workspace")(token) ||
                isTint(token),
            },
            {
              destination: name(outputs.desktopJson),
              format: "json/nested",
              filter: group("accent-scale", "radius", "font"),
            },
          ],
        },
        core: {
          transforms: ["attribute/cti", "name/camel"],
          buildPath: at(outputs.corePalette),
          files: [
            {
              destination: name(outputs.corePalette),
              format: "rust/course-palette",
              filter: isPalette,
            },
          ],
        },
      },
    }),
    new StyleDictionary({
      ...options,
      source: [tokens("color.dark.json")],
      platforms: {
        desktop: {
          transforms: cssTransforms,
          buildPath: at(outputs.desktopDarkCss),
          files: [
            {
              destination: name(outputs.desktopDarkCss),
              format: "css/isct-dark",
            },
          ],
        },
        ios: {
          transforms: swiftTransforms,
          buildPath: at(outputs.swiftDark),
          files: [
            {
              destination: name(outputs.swiftDark),
              format: "ios-swift/class.swift",
              filter: group("color"),
              options: { className: "IsctTokensDark", import: ["SwiftUI"] },
            },
          ],
        },
        android: {
          transforms: composeTransforms,
          buildPath: at(outputs.composeDark),
          files: [
            {
              destination: name(outputs.composeDark),
              format: "compose/object",
              filter: group("color"),
              options: {
                className: "IsctTokensDark",
                packageName: "app.isct.design",
              },
            },
          ],
        },
      },
    }),
    new StyleDictionary({
      ...options,
      source: [...light, path.join(designDir, "platforms", "mobile.json")],
      platforms: {
        ios: {
          transforms: swiftTransforms,
          buildPath: at(outputs.swiftLight),
          files: [
            {
              destination: name(outputs.swiftLight),
              format: "ios-swift/class.swift",
              filter: mobileToken,
              options: { className: "IsctTokens", import: ["SwiftUI"] },
            },
          ],
        },
        android: {
          transforms: composeTransforms,
          buildPath: at(outputs.composeLight),
          files: [
            {
              destination: name(outputs.composeLight),
              format: "compose/object",
              filter: mobileToken,
              options: {
                className: "IsctTokens",
                packageName: "app.isct.design",
              },
            },
          ],
        },
      },
    }),
  ];
  for (const run of runs) await run.buildAllPlatforms();
}

export async function staleOutputs() {
  const out = await mkdtemp(path.join(tmpdir(), "isct-design-"));
  try {
    await build(out);
    const stale = [];
    for (const file of Object.values(outputs)) {
      // Native SDK assets are generated under ignored design/dist. Only
      // versioned desktop/Core outputs have a committed baseline to compare.
      if (file.startsWith("design/dist/")) continue;
      const fresh = await readFile(path.join(out, file), "utf8");
      const committed = await readFile(path.join(repoRoot, file), "utf8").catch(
        () => null,
      );
      if (fresh !== committed) stale.push(file);
    }
    return stale;
  } finally {
    await rm(out, { recursive: true, force: true });
  }
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  if (process.argv.includes("--check")) {
    const stale = await staleOutputs();
    if (stale.length) {
      console.error(
        `Stale design tokens; run yarn design:tokens:\n${stale.join("\n")}`,
      );
      process.exit(1);
    }
  } else {
    await build(repoRoot);
  }
}
