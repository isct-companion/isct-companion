#!/usr/bin/env node
// Manual acceptance checks: validate the table, render it, and work out which
// checks a pending change has invalidated.
//
// The checks describe behaviour CI cannot reach (real credentials, provider
// consent screens, signed bundles, hardware, native shells). Their *structure*
// is enforced automatically; their *results* are supplied by a person or an
// agent that ran them. What keeps the table from rotting is `stale`: it
// compares each check's recorded commit against the commits that touched the
// paths the check covers, so a change to those paths names the checks that
// must be re-run.
//
//   node scripts/checks/manual-acceptance.mjs validate
//   node scripts/checks/manual-acceptance.mjs render [--check]
//   node scripts/checks/manual-acceptance.mjs stale [--json]
//   node scripts/checks/manual-acceptance.mjs sheet <ID>
//   node scripts/checks/manual-acceptance.mjs record <ID> --result pass \
//        --by human --evidence <path> [--notes "..."] [--blocked-by "..."]

import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { parse, parseDocument } from "yaml";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const source = join(root, "docs/verification/manual-checks.yaml");
const rendered = join(root, "docs/verification/manual-acceptance.md");

const RESULTS = new Set(["pass", "fail", "unreached"]);
const AREAS = new Set([
  "school",
  "identity",
  "cloud",
  "ocr",
  "desktop",
  "native",
  "release",
]);
const GENERATED_BANNER =
  "<!-- Generated by scripts/checks/manual-acceptance.mjs from manual-checks.yaml. Do not edit. -->";

// --------------------------------------------------------------------------
// git
// --------------------------------------------------------------------------

const git = (...args) =>
  execFileSync("git", args, { cwd: root, encoding: "utf8" }).trim();

function trackedFiles() {
  return git("ls-files").split("\n").filter(Boolean);
}

/** Converts a repository-relative glob into a regular expression. */
export function globToRegExp(glob) {
  let out = "^";
  for (let index = 0; index < glob.length; index += 1) {
    const character = glob[index];
    if (character === "*") {
      if (glob[index + 1] === "*") {
        // `**/` spans directories; a bare `**` spans anything.
        if (glob[index + 2] === "/") {
          out += "(?:[^/]+/)*";
          index += 2;
        } else {
          out += ".*";
          index += 1;
        }
      } else {
        out += "[^/]*";
      }
    } else if (character === "?") {
      out += "[^/]";
    } else {
      out += character.replace(/[.+^${}()|[\]\\]/g, "\\$&");
    }
  }
  return new RegExp(`${out}$`);
}

function matchesAny(path, globs) {
  return globs.some((glob) => globToRegExp(glob).test(path));
}

function lastCommitFor(globs) {
  const output = git("log", "-1", "--format=%H", "--", ...globs);
  return output || undefined;
}

function isAncestor(ancestor, descendant) {
  if (ancestor === descendant) return true;
  try {
    execFileSync("git", ["merge-base", "--is-ancestor", ancestor, descendant], {
      cwd: root,
      stdio: "ignore",
    });
    return true;
  } catch {
    return false;
  }
}

// Names only: porcelain status starts an unstaged line with a space, which
// git()'s trim would eat, and writes a rename as "old -> new".
function pendingChanges(globs) {
  const changed = git("diff", "--name-only", "HEAD", "--", ...globs);
  const untracked = git(
    "ls-files",
    "--others",
    "--exclude-standard",
    "--",
    ...globs,
  );
  return [...new Set(`${changed}\n${untracked}`.split("\n").filter(Boolean))];
}

// --------------------------------------------------------------------------
// load / validate
// --------------------------------------------------------------------------

function load() {
  return parse(readFileSync(source, "utf8"));
}

export function validate(doc, files = trackedFiles()) {
  const problems = [];
  if (doc?.version !== 1) problems.push("version must be 1");

  const personas = new Map();
  for (const persona of doc?.personas ?? []) {
    if (!persona?.id) problems.push("a persona has no id");
    else if (personas.has(persona.id))
      problems.push(`duplicate persona ${persona.id}`);
    else personas.set(persona.id, persona);
    for (const field of [
      "label",
      "identity",
      "context",
      "behaviour",
      "language",
      "device",
    ]) {
      if (!persona?.[field])
        problems.push(`persona ${persona?.id}: ${field} is required`);
    }
  }

  const seen = new Set();
  for (const check of doc?.checks ?? []) {
    const at = `check ${check?.id ?? "<missing id>"}`;
    if (!check?.id) problems.push("a check has no id");
    else if (seen.has(check.id))
      problems.push(`duplicate check id ${check.id}`);
    else seen.add(check.id);

    for (const field of [
      "area",
      "title",
      "preconditions",
      "observe",
      "expected",
      "why_manual",
    ]) {
      if (!check?.[field] || String(check[field]).trim() === "") {
        problems.push(`${at}: ${field} is required`);
      }
    }
    if (check?.area && !AREAS.has(check.area)) {
      problems.push(`${at}: unknown area ${check.area}`);
    }
    if (check?.persona && !personas.has(check.persona)) {
      problems.push(`${at}: persona ${check.persona} is not defined`);
    }

    const steps = check?.steps;
    if (!Array.isArray(steps) || steps.length === 0) {
      problems.push(`${at}: at least one step is required`);
    } else {
      steps.forEach((step, index) => {
        // A step without a reason is either redundant or its author did not
        // know what it was looking for. Both are rejected.
        if (!step?.action?.trim())
          problems.push(`${at}: step ${index + 1} has no action`);
        if (!step?.reason?.trim())
          problems.push(`${at}: step ${index + 1} has no reason`);
      });
    }

    if (!Array.isArray(check?.covers) || check.covers.length === 0) {
      problems.push(`${at}: covers is required`);
    } else {
      for (const glob of check.covers) {
        const hits = files.filter((file) => globToRegExp(glob).test(file));
        if (hits.length === 0)
          problems.push(`${at}: covers ${glob} matches no tracked file`);
      }
      // A check whose whole surface is already exercised by a suite belongs in
      // `tests/`, not here.
      if (check.covers.every((glob) => glob.startsWith("tests/"))) {
        problems.push(`${at}: covers only test files; automate it instead`);
      }
    }

    if (check?.verified != null) {
      const verified = check.verified;
      for (const field of ["version", "date", "commit", "by", "result"]) {
        if (!verified?.[field])
          problems.push(`${at}: verified.${field} is required`);
      }
      if (verified?.result && !RESULTS.has(verified.result)) {
        problems.push(
          `${at}: verified.result must be one of ${[...RESULTS].join(", ")}`,
        );
      }
      if (verified?.date && !/^\d{4}-\d{2}-\d{2}$/.test(verified.date)) {
        problems.push(`${at}: verified.date must be YYYY-MM-DD`);
      }
      if (verified?.result === "unreached" && !verified?.blocked_by) {
        problems.push(`${at}: an unreached result must record blocked_by`);
      }
      if (verified?.result !== "unreached" && !verified?.evidence) {
        problems.push(`${at}: a pass or fail result must record evidence`);
      }
    }
  }
  return problems;
}

// --------------------------------------------------------------------------
// staleness
//
// Two different questions, deliberately kept apart:
//
//   invalidated — this check passed before, and a change since then touched the
//                 paths it covers, so its result can no longer be trusted.
//   gap         — this check has never been run, or could not be run.
//
// Only the first is a prompt. Reporting the second as "needs attention" would
// drown the signal, and a check that has never run is a known hole rather than
// something the current change broke.
// --------------------------------------------------------------------------

export function invalidated(check, options = {}) {
  const verified = check.verified;
  if (!verified?.commit || verified.result === "unreached") return [];
  const reasons = [];
  let newest;
  try {
    newest = lastCommitFor(check.covers);
  } catch {
    reasons.push("git history unavailable");
  }
  if (newest && !isAncestor(verified.commit, newest)) {
    reasons.push(`covered paths changed after ${verified.commit.slice(0, 7)}`);
  }
  if (!options.skipPending) {
    const pending = pendingChanges(check.covers);
    if (pending.length)
      reasons.push(`uncommitted change: ${pending.slice(0, 3).join(", ")}`);
  }
  return reasons;
}

export function gap(check) {
  if (!check.verified) return "never verified";
  if (check.verified.result === "unreached") {
    return `unreached: ${check.verified.blocked_by}`;
  }
  return undefined;
}

export function staleness(check, options = {}) {
  const reasons = invalidated(check, options);
  const missing = gap(check);
  if (missing) reasons.push(missing);
  return {
    stale: reasons.length > 0,
    reasons,
    invalidated: invalidated(check, options),
    gap: missing,
  };
}

// --------------------------------------------------------------------------
// render
// --------------------------------------------------------------------------

function status(check, state) {
  if (check.verified?.result === "unreached") return "**unreached**";
  if (!check.verified) return "—";
  const mark = check.verified.result === "pass" ? "pass" : "**fail**";
  return state.invalidated.length ? `${mark} ⚠` : mark;
}

export function render(doc, options = {}) {
  const checks = doc.checks ?? [];
  const personas = new Map(
    (doc.personas ?? []).map((persona) => [persona.id, persona]),
  );
  const computed = new Map(
    checks.map((check) => [
      check.id,
      options.compute
        ? staleness(check, { skipPending: options.skipPending })
        : { stale: false, reasons: [], invalidated: [], gap: undefined },
    ]),
  );

  const lines = [GENERATED_BANNER, "", "# Manual acceptance", ""];
  lines.push(
    "Behaviour that CI cannot reach, written to be executed by a person or by an",
    "agent driving the real GUI. The source of truth is",
    "[`manual-checks.yaml`](manual-checks.yaml); this file is rendered from it.",
    "",
    "```sh",
    "yarn verify:manual stale     # which checks a pending change invalidates",
    "yarn verify:manual sheet ID  # a run sheet for one check and its persona",
    "```",
    "",
    "`pass` and `fail` carry evidence. `unreached` means the flow could not be",
    "attempted at all, and records what blocked it: a silently missing row is how",
    "an unverified area becomes an assumed-good one.",
    "",
  );

  if (options.compute) {
    const invalidated = checks.filter(
      (check) => computed.get(check.id).invalidated.length > 0,
    );
    const gaps = checks.filter((check) => computed.get(check.id).gap);
    lines.push("## State", "");
    if (invalidated.length) {
      lines.push(
        `**${invalidated.length} of ${checks.length} checks must be re-run before the next release.**`,
        "",
      );
      for (const check of invalidated) {
        lines.push(
          `- \`${check.id}\` — ${computed.get(check.id).invalidated.join("; ")}`,
        );
      }
      lines.push("");
    } else {
      lines.push(`No check has been invalidated by a change.`, "");
    }
    if (gaps.length) {
      lines.push(
        `**${gaps.length} checks have never been run or could not be run:**`,
        "",
      );
      for (const check of gaps) {
        lines.push(`- \`${check.id}\` — ${computed.get(check.id).gap}`);
      }
      lines.push("");
    }
  }

  lines.push("## Status", "");
  lines.push("| Check | Area | Persona | Result | Covers |");
  lines.push("| --- | --- | --- | --- | --- |");
  for (const check of checks) {
    const persona = personas.get(check.persona);
    const verified = check.verified;
    const when = verified
      ? `${verified.date} · ${verified.by} · \`${verified.commit.slice(0, 7)}\``
      : "not run";
    lines.push(
      `| \`${check.id}\` | ${check.area} | ${persona?.label ?? check.persona} | ` +
        `${status(check, computed.get(check.id))}<br>${when} | ${check.covers.join("<br>")} |`,
    );
  }
  lines.push("");

  lines.push("## Personas", "");
  for (const persona of doc.personas ?? []) {
    lines.push(`### ${persona.label} (\`${persona.id}\`)`, "");
    lines.push(
      `Identity: ${persona.identity} · Language: ${persona.language} · Device: ${persona.device}`,
      "",
      persona.context.trim(),
      "",
      persona.behaviour.trim(),
      "",
    );
  }

  lines.push("## Checks", "");
  for (const check of checks) {
    const persona = personas.get(check.persona);
    const state = computed.get(check.id);
    lines.push(`### ${check.title} (\`${check.id}\`)`, "");
    lines.push(
      `**Area** ${check.area} · **Persona** ${persona?.label ?? check.persona} · ` +
        `**Result** ${status(check, state)}`,
      "",
    );
    if (state.invalidated.length) {
      lines.push(`> Needs re-running: ${state.invalidated.join("; ")}`, "");
    }
    if (state.gap) {
      lines.push(`> Not verified: ${state.gap}`, "");
    }
    lines.push("**Preconditions**", "", check.preconditions.trim(), "");
    lines.push("**Steps**", "");
    check.steps.forEach((step, index) => {
      lines.push(`${index + 1}. ${step.action.trim().replace(/\n/g, "\n   ")}`);
      lines.push(`   - *Why:* ${step.reason.trim().replace(/\n/g, "\n     ")}`);
    });
    lines.push("");
    lines.push("**Where to look**", "", check.observe.trim(), "");
    lines.push("**Expected**", "", check.expected.trim(), "");
    lines.push("**Why this is manual**", "", check.why_manual.trim(), "");
    lines.push(
      "**Covers**",
      "",
      ...check.covers.map((glob) => `- \`${glob}\``),
      "",
    );
    if (check.verified) {
      const verified = check.verified;
      lines.push(
        `**Last recorded** ${verified.result} · ${verified.date} · ${verified.by} · ` +
          `\`${verified.commit}\` · \`${verified.version}\``,
        "",
      );
      if (verified.blocked_by)
        lines.push(`Blocked by: ${verified.blocked_by}`, "");
      if (verified.notes) lines.push(verified.notes.trim(), "");
      if (verified.evidence)
        lines.push(`Evidence: \`${verified.evidence}\``, "");
    } else {
      lines.push("**Last recorded** never run", "");
    }
  }
  return `${lines
    .join("\n")
    .replace(/\n{3,}/g, "\n\n")
    .trimEnd()}\n`;
}

