export function runSheet(doc, id) {
  const check = (doc.checks ?? []).find((candidate) => candidate.id === id);
  if (!check) throw new Error(`no check with id ${id}`);
  const persona = (doc.personas ?? []).find(
    (candidate) => candidate.id === check.persona,
  );
  const lines = [
    `# Run sheet: ${check.title}`,
    "",
    `Check \`${check.id}\` · area ${check.area}`,
    "",
    "You are about to act as a specific person. Adopt this persona completely:",
    "read only what they could read, know only what they would know, and make",
    "their mistakes. Do not use knowledge they would not have.",
    "",
    `## Persona: ${persona.label} (\`${persona.id}\`)`,
    "",
    `- Identity: ${persona.identity}`,
    `- Language: ${persona.language}`,
    `- Device: ${persona.device}`,
    "",
    persona.context.trim(),
    "",
    persona.behaviour.trim(),
    "",
    "## Preconditions",
    "",
    check.preconditions.trim(),
    "",
    "## Steps",
    "",
    "Record what you actually observed for each step. If a step cannot be",
    "reached, say what blocked it and stop rather than working around it.",
    "",
  ];
  check.steps.forEach((step, index) => {
    lines.push(
      `### Step ${index + 1}`,
      "",
      step.action.trim(),
      "",
      `*Why this step exists:* ${step.reason.trim()}`,
      "",
      "Observed: ",
      "",
    );
  });
  lines.push(
    "## Where to look",
    "",
    check.observe.trim(),
    "",
    "## Expected",
    "",
    check.expected.trim(),
    "",
    "## Verdict",
    "",
    "Record one of `pass`, `fail` or `unreached`, with evidence a reviewer can",
    "open. `unreached` is the honest answer when the flow could not be attempted;",
    "do not record `pass` for a flow you did not complete.",
    "",
    "```sh",
    `yarn verify:manual record ${check.id} --result <pass|fail|unreached> \\`,
    '  --by <human|agent> --evidence <path> [--notes "..."] [--blocked-by "..."]',
    "```",
    "",
    "## Failure shape",
    "",
    "For each failure record three lines: what is wrong, what should happen, and",
    "where to see it. Quote the evidence rather than paraphrasing it.",
    "",
  );
  return `${lines
    .join("\n")
    .replace(/\n{3,}/g, "\n\n")
    .trimEnd()}\n`;
}

// --------------------------------------------------------------------------
// record
// --------------------------------------------------------------------------

export function record(doc, id, update) {
  const check = (doc.checks ?? []).find((candidate) => candidate.id === id);
  if (!check) throw new Error(`no check with id ${id}`);
  if (!RESULTS.has(update.result)) {
    throw new Error(`--result must be one of ${[...RESULTS].join(", ")}`);
  }
  if (update.result === "unreached" && !update.blockedBy) {
    throw new Error("--blocked-by is required for an unreached result");
  }
  if (update.result !== "unreached" && !update.evidence) {
    throw new Error("--evidence is required for a pass or fail result");
  }
  check.verified = {
    version: update.version ?? readVersion(),
    date: update.date ?? new Date().toISOString().slice(0, 10),
    commit: update.commit ?? git("rev-parse", "HEAD"),
    by: update.by ?? "human",
    result: update.result,
    ...(update.notes ? { notes: update.notes } : {}),
    ...(update.blockedBy ? { blocked_by: update.blockedBy } : {}),
    ...(update.evidence ? { evidence: update.evidence } : {}),
  };
  return check;
}

/**
 * Writes a recorded result back into the source file.
 *
 * Uses the document API rather than `stringify` so the file's own header
 * comments — which explain why the file is shaped this way — survive.
 */
function writeRecord(id, update) {
  const document = parseDocument(readFileSync(source, "utf8"));
  const checks = document.get("checks");
  const index = checks.items.findIndex((item) => item.get("id") === id);
  if (index < 0) throw new Error(`no check with id ${id}`);
  const verified = record({ checks: checks.toJSON() }, id, update).verified;
  checks.items[index].set("verified", verified);
  writeFileSync(source, document.toString());
  return verified;
}

function readVersion() {
  return JSON.parse(readFileSync(join(root, "package.json"), "utf8")).version;
}

// --------------------------------------------------------------------------
// cli
// --------------------------------------------------------------------------

function flag(args, name) {
  const at = args.indexOf(`--${name}`);
  return at >= 0 ? args[at + 1] : undefined;
}

function fail(message, details = []) {
  process.stderr.write(`${message}\n`);
  for (const detail of details) process.stderr.write(`  - ${detail}\n`);
  process.exitCode = 1;
}

function main() {
  const [command, ...args] = process.argv.slice(2);
  const doc = load();

  switch (command) {
    case "validate": {
      const problems = validate(doc);
      if (problems.length) return fail("manual checks are invalid", problems);
      process.stdout.write(
        `${doc.checks.length} checks and ${doc.personas.length} personas are valid.\n`,
      );
      return;
    }
    case "render": {
      const next = render(doc, { compute: true, skipPending: true });
      if (args.includes("--check")) {
        const current = (() => {
          try {
            return readFileSync(rendered, "utf8");
          } catch {
            return "";
          }
        })();
        if (current !== next) {
          return fail("docs/verification/manual-acceptance.md is out of date", [
            "run `yarn verify:manual render`",
          ]);
        }
        process.stdout.write("Rendered table is up to date.\n");
        return;
      }
      writeFileSync(rendered, next);
      process.stdout.write(`Wrote ${relative(root, rendered)}.\n`);
      return;
    }
    case "stale": {
      const rows = (doc.checks ?? []).map((check) => ({
        id: check.id,
        area: check.area,
        persona: check.persona,
        result: check.verified?.result ?? "never",
        ...staleness(check),
      }));
      if (args.includes("--json")) {
        process.stdout.write(`${JSON.stringify(rows, null, 2)}\n`);
        return;
      }
      const invalidatedRows = rows.filter((row) => row.invalidated.length > 0);
      const gapRows = rows.filter((row) => row.gap);
      if (invalidatedRows.length) {
        const areas = [...new Set(invalidatedRows.map((row) => row.area))].join(
          ", ",
        );
        process.stdout.write(
          `${invalidatedRows.length} of ${rows.length} manual checks were invalidated by changes (${areas}):\n`,
        );
        for (const row of invalidatedRows) {
          process.stdout.write(`  ${row.id} — ${row.invalidated.join("; ")}\n`);
        }
      } else {
        process.stdout.write("No manual check was invalidated by a change.\n");
      }
      if (gapRows.length) {
        process.stdout.write(
          `\n${gapRows.length} of ${rows.length} manual checks have no current result:\n`,
        );
        for (const row of gapRows) {
          process.stdout.write(`  ${row.id} — ${row.gap}\n`);
        }
      }
      return;
    }
    case "sheet": {
      const id = args.find((arg) => !arg.startsWith("--"));
      if (!id) return fail("usage: verify:manual sheet <ID>");
      process.stdout.write(runSheet(doc, id));
      return;
    }
    case "record": {
      const id = args.find((arg) => !arg.startsWith("--"));
      if (!id) return fail("usage: verify:manual record <ID> --result <r> ...");
      const verified = writeRecord(id, {
        result: flag(args, "result"),
        by: flag(args, "by"),
        evidence: flag(args, "evidence"),
        notes: flag(args, "notes"),
        blockedBy: flag(args, "blocked-by"),
        version: flag(args, "version"),
        commit: flag(args, "commit"),
        date: flag(args, "date"),
      });
      writeFileSync(
        rendered,
        render(load(), { compute: true, skipPending: true }),
      );
      process.stdout.write(`Recorded ${id} as ${verified.result}.\n`);
      return;
    }
    default:
      return fail(
        "usage: verify:manual <validate|render|stale|sheet|record> [args]",
      );
  }
}

if (
  process.argv[1] &&
  resolve(process.argv[1]) === fileURLToPath(import.meta.url)
) {
  main();
}
